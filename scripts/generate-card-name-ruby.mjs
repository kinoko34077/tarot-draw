// Regenerate: npm install --no-save aozora-wasm@0.5.0 && node scripts/generate-card-name-ruby.mjs
// The committed output is deterministic and imported by the UI; no WASM loads in the browser.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const api = await import('aozora-wasm');
const packageRoot = dirname(fileURLToPath(import.meta.resolve('aozora-wasm')));
const wasm = await readFile(join(packageRoot, 'aozora_wasm_bg.wasm'));
api.initSync({ module: Uint8Array.from(wasm).buffer });
api.prewarm();

const suits = {
  wands: ['杖', 'ワンド'],
  cups: ['盃', 'カップ'],
  swords: ['剣', 'ソード'],
  pentacles: ['金貨', 'ペンタクル']
};
const ranks = {
  ace: ['一', 'エース'],
  page: ['小姓', 'ペイジ'],
  knight: ['騎士', 'ナイト'],
  queen: ['女王', 'クイーン'],
  king: ['王', 'キング']
};
const numericRanks = ['2','3','4','5','6','7','8','9','10'];

function renderRuby(base, reading) {
  const source = `｜${base}《${reading}》`;
  const document = new api.Document(source);
  try {
    const diagnostics = document.diagnostics();
    if (Array.isArray(diagnostics) && diagnostics.length > 0) {
      throw new Error(`aozora-wasm diagnostics for ${source}: ${JSON.stringify(diagnostics)}`);
    }
    const html = document.toHtml();
    const match = html.match(/<ruby\b[\s\S]*?<\/ruby>/i);
    if (!match) throw new Error(`aozora-wasm did not emit ruby for ${source}: ${html}`);
    return match[0];
  } finally {
    document.free();
  }
}

const output = {};
for (const [suit, [suitBase, suitReading]] of Object.entries(suits)) {
  const suitHtml = renderRuby(suitBase, suitReading);

  for (const rank of ['ace', ...numericRanks, 'page', 'knight', 'queen', 'king']) {
    const cardId = `minor.${suit}.${rank}`;
    if (numericRanks.includes(rank)) {
      output[cardId] = {
        source: `｜${suitBase}《${suitReading}》の${rank}`,
        html: `${suitHtml}の${rank}`,
        compact: `${suitBase}の${rank}`,
        plain: `${suitBase}（${suitReading}）の${rank}`
      };
      continue;
    }

    const [rankBase, rankReading] = ranks[rank];
    const rankHtml = renderRuby(rankBase, rankReading);
    output[cardId] = {
      source: `｜${suitBase}《${suitReading}》の｜${rankBase}《${rankReading}》`,
      html: `${suitHtml}の${rankHtml}`,
      compact: `${suitBase}の${rankBase}`,
      plain: `${suitBase}（${suitReading}）の${rankBase}（${rankReading}）`
    };
  }
}

if (Object.keys(output).length !== 56) throw new Error('Expected 56 Minor Arcana display entries.');

const generated = `// Generated by scripts/generate-card-name-ruby.mjs using aozora-wasm ${api.version()}.
// Do not hand-edit ruby HTML; edit the generator source notation instead.
export const MINOR_CARD_DISPLAY = Object.freeze(${JSON.stringify(output, null, 2)});
`;
await writeFile(resolve('web/card-name-ruby.js'), generated, 'utf8');
console.log(JSON.stringify({ version: api.version(), schemaVersion: api.schemaVersion(), cards: Object.keys(output).length }));
